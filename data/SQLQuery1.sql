ALTER PROCEDURE [dbo].[sp_PhieuKham_TongHop]
    @MaPhieu INT
AS
BEGIN
    -- Tập kết quả 1: Thông tin hành chính & Bác sĩ & Chẩn đoán
    SELECT 
        pk.MAPHIEU, pk.MABENHNHAN, pk.NGAYKHAM, pk.KHOA, pk.LYDOKHAM,
