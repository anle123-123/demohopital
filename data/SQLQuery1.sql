-- 1. Sửa thủ tục Lấy danh sách (ListToday)
CREATE OR ALTER PROCEDURE [dbo].[sp_LaySo_ListToday]
    @Khoa NVARCHAR(50) = NULL
AS
BEGIN
    SET NOCOUNT ON;

    -- Chọn ĐÚNG THỨ TỰ cột để khớp với Python:
    -- 0: ID, 1: KHOA, 2: SO_THU_TU, 3: HOVATEN, 4: STATUS, 5: CREATED_AT
    SELECT ID, KHOA, SO_THU_TU, HOVATEN, STATUS, CREATED_AT
    FROM DBO.LAYSO_ONLINE
    WHERE CAST(CREATED_AT AS DATE) = CAST(GETDATE() AS DATE)
      AND STATUS IN ('WAITING', 'CALLING')
      AND (@Khoa IS NULL OR @Khoa = '' OR KHOA = @Khoa)
    ORDER BY 
        CASE WHEN STATUS = 'CALLING' THEN 0 ELSE 1 END, 
        SO_THU_TU ASC;
END
GO

-- 2. Sửa thủ tục Lấy người hiện tại (GetCurrent)
CREATE OR ALTER PROCEDURE [dbo].[sp_LaySo_GetCurrent]
    @Khoa NVARCHAR(50)
AS
BEGIN
    SET NOCOUNT ON;

    -- Chọn ĐÚNG THỨ TỰ cột:
    SELECT TOP 1 ID, KHOA, SO_THU_TU, HOVATEN, STATUS, CREATED_AT
    FROM DBO.LAYSO_ONLINE
    WHERE KHOA = @Khoa 
      AND STATUS = 'CALLING'
      AND CAST(CREATED_AT AS DATE) = CAST(GETDATE() AS DATE);
END
GO

-- 3. Sửa thủ tục Gọi số tiếp theo (Next)
CREATE OR ALTER PROCEDURE [dbo].[sp_LaySo_Next]
    @Khoa NVARCHAR(50)
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @NextID INT;

    SELECT TOP 1 @NextID = ID
    FROM DBO.LAYSO_ONLINE
    WHERE KHOA = @Khoa AND STATUS = 'WAITING'
      AND CAST(CREATED_AT AS DATE) = CAST(GETDATE() AS DATE)
    ORDER BY SO_THU_TU ASC;

    IF @NextID IS NOT NULL
    BEGIN
        UPDATE DBO.LAYSO_ONLINE SET STATUS = 'SKIPPED' WHERE KHOA = @Khoa AND STATUS = 'CALLING';
        UPDATE DBO.LAYSO_ONLINE SET STATUS = 'CALLING' WHERE ID = @NextID;
        
        -- Trả về đúng thứ tự cột
        SELECT ID, KHOA, SO_THU_TU, HOVATEN, STATUS, CREATED_AT
        FROM DBO.LAYSO_ONLINE WHERE ID = @NextID;
    END
END
