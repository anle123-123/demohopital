ALTER PROCEDURE [dbo].[sp_PhieuKham_TongHop]
    @MaPhieu INT
AS
BEGIN
    -- Tập kết quả 1: Thông tin hành chính (Giữ nguyên)
    SELECT pk.*, bn.HOVATEN, bn.NGAYSINH, bn.SODIENTHOAI, bn.DIACHI, bn.QUEQUAN, nv.HOVATEN as TEN_BAC_SI
    FROM DBO.PHIEUKHAM pk
    JOIN DBO.HOSOBENHNHAN bn ON pk.MABENHNHAN = bn.MABENHNHAN
    LEFT JOIN DBO.QUANLINHANVIEN nv ON pk.MANHANVIEN = nv.MANHANVIEN
    WHERE pk.MAPHIEU = @MaPhieu;

    -- Tập kết quả 2: Chi tiết chi phí
    -- Lấy Phí khám (Lấy từ bảng DICHVU để tránh bị 0đ)
    SELECT 
        N'Dịch vụ' AS LOAI, 
        N'Phí khám' AS MOTA, 
        1 AS SOLUONG, 
        ISNULL(dv.DON_GIA, 300000) AS DONGIA, -- Mặc định 300k nếu không tìm thấy
        ISNULL(dv.DON_GIA, 300000) AS THANHTIEN
    FROM DBO.PHIEUKHAM pk
    LEFT JOIN DBO.DICHVU dv ON dv.TEN_CHI_PHI = N'Khám cấp cứu' -- Hoặc loại khám tương ứng
    WHERE pk.MAPHIEU = @MaPhieu
    
    UNION ALL
    
    -- Lấy Xét nghiệm (Đã sửa lấy từ cột GIA)
    SELECT N'Xét nghiệm' AS LOAI, CHIDINH AS MOTA, 1 AS SOLUONG, ISNULL(GIA, 0) AS DONGIA, ISNULL(GIA, 0) AS THANHTIEN
    FROM DBO.XETNGHIEM 
    WHERE MAPHIEU = @MaPhieu
    
    UNION ALL
    
    -- Lấy Thuốc
    SELECT N'Thuốc' AS LOAI, ct.TENTHUOC AS MOTA, ct.SOLUONG, ISNULL(t.GIA, 0) AS DONGIA, (ct.SOLUONG * ISNULL(t.GIA, 0)) AS THANHTIEN
    FROM DBO.DONTHUOC d
    JOIN DBO.DONTHUOC_CT ct ON d.MADON = ct.MADON
    LEFT JOIN DBO.THUOC t ON ct.MATHUOC = t.MATHUOC
    WHERE d.MAPHIEU = @MaPhieu;
END
ALTER PROCEDURE [dbo].[sp_PhieuKham_TongHop]
    @MaPhieu INT
AS
BEGIN
    -- Tập kết quả 1: Header (Thông tin hành chính & Chẩn đoán)
    SELECT 
        pk.MAPHIEU, 
        pk.MABENHNHAN, 
        CONVERT(VARCHAR(19), pk.NGAYKHAM, 120) AS NGAYKHAM,
        pk.KHOA, 
        pk.LYDOKHAM, 
        pk.CHANDOAN AS CHANDOAN_SOBO,
        bn.HOVATEN, 
        CONVERT(VARCHAR(10), bn.NGAYSINH, 103) AS NGAYSINH, 
        bn.SODIENTHOAI, 
        bn.DIACHI, 
        bn.QUEQUAN,
        nv.HOVATEN AS BACSI, -- Lấy tên bác sĩ từ bảng nhân viên
        -- Gộp các mã ICD10 từ bảng CHANDOANCT
        STUFF((SELECT ', ' + ICD10 FROM DBO.CHANDOANCT WHERE MAPHIEU = pk.MAPHIEU FOR XML PATH('')), 1, 2, '') AS ICD10,
        -- Gộp các mô tả chi tiết chẩn đoán
        STUFF((SELECT '; ' + MOTA FROM DBO.CHANDOANCT WHERE MAPHIEU = pk.MAPHIEU FOR XML PATH('')), 1, 2, '') AS CHANDOAN_CHITIET
    FROM DBO.PHIEUKHAM pk
    JOIN DBO.HOSOBENHNHAN bn ON pk.MABENHNHAN = bn.MABENHNHAN
    LEFT JOIN DBO.QUANLINHANVIEN nv ON pk.MANHANVIEN = nv.MANHANVIEN
    WHERE pk.MAPHIEU = @MaPhieu;

    -- Tập kết quả 2: Chi tiết chi phí
    SELECT N'Dịch vụ' AS LOAI, N'Phí khám' AS MOTA, 1 AS SOLUONG, ISNULL(PHIKHAM, 300000) AS DONGIA, ISNULL(PHIKHAM, 300000) AS THANHTIEN
    FROM DBO.PHIEUKHAM WHERE MAPHIEU = @MaPhieu
    UNION ALL
    SELECT N'Xét nghiệm' AS LOAI, CHIDINH AS MOTA, 1 AS SOLUONG, ISNULL(GIA, 0) AS DONGIA, ISNULL(GIA, 0) AS THANHTIEN
    FROM DBO.XETNGHIEM WHERE MAPHIEU = @MaPhieu
    UNION ALL
